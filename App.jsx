// rate: ความเร็ว (RATE_NORMAL / RATE_SLOW)
function speak(parts, rate = RATE_NORMAL) {
  const list = (Array.isArray(parts) ? parts : [parts]).map(cleanText).filter(Boolean);
  if (!list.length) return;
  if (googleVoiceOn && Date.now() >= googleBlockedUntil && googleSpeak(list, rate)) return;
  browserSpeak(list, rate);
}

