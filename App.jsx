function BlendPage({ say, done, onDone }) {
  const [word, setWord] = useState("กา");
  const [cat, setCat] = useState("all");
  const inputRef = useRef(null);
  const sel = useRef(null); // ตำแหน่งเคอร์เซอร์ล่าสุด {s, e}; null = ท้ายคำ
  const pendingCaret = useRef(null);

  useEffect(() => {
    if (pendingCaret.current !== null && inputRef.current) {
      const p = pendingCaret.current;
      pendingCaret.current = null;
      try { inputRef.current.setSelectionRange(p, p); } catch { /* ข้ามไป */ }
    }
  }, [word]);

  const remember = (el) => { sel.current = { s: el.selectionStart ?? 0, e: el.selectionEnd ?? 0 }; };

  const apply = (next, caret) => {
    const v = next.slice(0, MAX_WORD);
    const c = Math.min(caret, v.length);
    setWord(v);
    sel.current = { s: c, e: c };
    pendingCaret.current = c;
  };

  const range = () => {
    const len = word.length;
    if (!sel.current) return [len, len];
    const s = Math.min(sel.current.s, len);
    const e = Math.min(sel.current.e, len);
    return [Math.min(s, e), Math.max(s, e)];
  };

  const insert = (str) => {
    const [s, e] = range();
    apply(word.slice(0, s) + str + word.slice(e), s + str.length);
  };

  const backspace = () => {
    const [s, e] = range();
    if (s !== e) apply(word.slice(0, s) + word.slice(e), s);
    else if (s > 0) apply(word.slice(0, s - 1) + word.slice(s), s - 1);
  };

  const clear = () => apply("", 0);

  const choose = (w) => { apply(w, w.length); say(w); };

  // สุ่มจากคำที่มีความหมายจริงในพจนานุกรมเท่านั้น (เลือกหมวดได้) และไม่ซ้ำคำเดิม
  const random = () => {
    const pool = cat === "all" ? WORD_LIST : WORD_LIST.filter((w) => WORD_INDEX.get(w).some((s) => s.cat === cat));
    const current = normalizeThai(word);
    const choices = pool.length > 1 ? pool.filter((w) => w !== current) : pool;
    if (choices.length) choose(choices[Math.floor(Math.random() * choices.length)]);
  };

  return (
    <>
      <div style={{ ...S.card, maxWidth: 720 }}>
        <p style={{ marginTop: 0 }}>
          พิมพ์หรือกดปุ่มด้านล่างเพื่อสะกดคำ / 输入或点击下方按键拼词
        </p>
        <input
          ref={inputRef}
          value={word}
          onChange={(e) => { setWord(e.target.value.slice(0, MAX_WORD)); remember(e.target); }}
          onSelect={(e) => remember(e.target)}
          onKeyDown={(e) => e.key === "Enter" && say(word)}
          maxLength={MAX_WORD}
          lang="th"
          aria-label="คำภาษาไทย / 泰语单词"
          style={{ fontSize: 32, padding: 12, width: "100%", boxSizing: "border-box", border: "1px solid #d8c4e8", borderRadius: 10 }}
        />
        <div style={{ display: "flex", gap: 10, flexWrap: "wrap", alignItems: "center", marginTop: 14 }}>
          <button type="button" style={S.primary} onClick={() => say(word)}>🔊 听发音 / ฟังเสียง</button>
          <button type="button" style={S.secondary} onMouseDown={keepFocus} onClick={backspace}>⌫ ลบ / 退格</button>
          <button type="button" style={S.secondary} onClick={clear}>✕ ล้าง / 清空</button>
          <button type="button" style={S.primary} onClick={random}>🎲 สุ่มคำ / 随机单词</button>
          <select
            value={cat}
            onChange={(e) => setCat(e.target.value)}
            aria-label="หมวดคำสำหรับสุ่ม / 随机类别"
            style={{ ...S.secondary, padding: "11px 12px", fontWeight: 400 }}
          >
            {CATS.map(([id, th, zh]) => <option key={id} value={id}>{th} / {zh}</option>)}
          </select>
        </div>
        <p style={{ ...S.muted, fontSize: 13, marginBottom: 0 }}>
          เสียงอ่านใช้ระบบสังเคราะห์เสียงของเบราว์เซอร์ คุณภาพขึ้นอยู่กับอุปกรณ์ · เปิด "พูดช้า" ที่แถบด้านบนเพื่อฟังชัดขึ้น
        </p>
      </div>

      <MeaningCard word={word} say={say} />

      <KeyPad onKey={insert} />

      <div style={{ ...S.card, marginTop: 18 }}>
        <h3 style={{ marginTop: 0 }}>ตัวอย่าง / 示例</h3>
        <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
          {STARTERS.map((w) => {
            const s = WORD_INDEX.get(w)[0];
            return (
              <button type="button" key={w} style={S.secondary} onClick={() => choose(w)}>
                {s.emoji} {w} <span style={{ ...S.muted, fontWeight: 400, fontSize: 13 }}>· {s.zh}</span>
              </button>
            );
          })}
        </div>
      </div>

      <CompleteButton done={done} onClick={onDone} />
    </>
  );
}

