function normalizeThai(s) {
  return String(s ?? "")
    .normalize("NFC")
    .replace(/\s+/g, "")
    .replace(/ํา/g, "ำ")
    .replace(/ำ([่-๋])/g, "$1ำ")
    .replace(/([่-๋])([ัิ-ื็])/g, "$2$1");
}

