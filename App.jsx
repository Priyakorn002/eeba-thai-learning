// คืน true ถ้าเริ่มเล่นด้วยเสียง Google ได้ (ถ้าไม่ได้ ผู้เรียกจะใช้เสียงเบราว์เซอร์แทน)
function googleSpeak(list, rate) {
  const audio = getPlayer();
  if (!audio) return false;
  getSynth()?.cancel(); // กันเสียงของเบราว์เซอร์ที่ค้างอยู่ทับกับเสียง Google
  const token = ++playToken;
  const speed = rate < RATE_NORMAL ? 0.75 : 1; // โหมดพูดช้า = เล่นช้าลงโดยคงระดับเสียง
  // ส่งทั้งคำอ่านเป็นคำขอเดียว (เช่น "ดอ ชะ ดา") ให้ Google อ่านพยางค์ในบริบท ไม่เพี้ยนแบบอ่านพยางค์เดี่ยวโดด ๆ
  const urls = [googleTtsUrl(list.join(" "))];

  let i = 0;
  let stall = 0;
  const fail = () => {
    clearTimeout(stall);
    if (token !== playToken) return; // เสียงนี้ถูกแทนที่/หยุดไปแล้ว ไม่ต้องทำอะไร
    playToken++;
    audio.onended = audio.onerror = audio.onplaying = null;
    try { audio.pause(); } catch { /* ข้ามไป */ }
    googleBlockedUntil = Date.now() + GOOGLE_COOLDOWN_MS;
    speechHooks.onGoogleFail?.();
    browserSpeak(list.slice(i), rate); // อ่านส่วนที่เหลือด้วยเสียงเบราว์เซอร์
  };
  const playPart = () => {
    if (token !== playToken) return;
    audio.onended = () => {
      clearTimeout(stall);
      i += 1;
      if (i < urls.length) setTimeout(playPart, PART_GAP_MS);
    };
    audio.onerror = fail;
    audio.onplaying = () => {
      clearTimeout(stall);
      speechHooks.onGoogleOk?.();
    };
    audio.defaultPlaybackRate = speed; // ตั้งก่อนเปลี่ยน src เพราะการโหลดใหม่จะรีเซ็ตความเร็ว
    audio.src = urls[i];
    audio.playbackRate = speed;
    if ("preservesPitch" in audio) audio.preservesPitch = true;
    stall = setTimeout(fail, GOOGLE_STALL_MS);
    const p = audio.play();
    if (p && p.catch) p.catch(fail);
  };
  playPart();
  return true;
}

/* ---- เสียงสังเคราะห์ของเบราว์เซอร์ (สำรอง) ---- */

let speakToken = 0;
let keepAlive = []; // เก็บ utterance ไว้ ป้องกันเบราว์เซอร์บางตัว (Chrome) เก็บกวาดก่อนอ่านจบ

function browserSpeak(list, rate) {
  const synth = getSynth();
  if (!synth || !list.length) return;
  stopGoogle(); // กันเสียง Google ที่ค้างอยู่ทับกัน
  const token = ++speakToken;
  // เสียงสะท้อน/เสียงซ้อนมักเกิดจากเสียงเก่ายังไม่หยุดสนิทแล้วเสียงใหม่เริ่มทับ (เช่น กดรัว)
  // จึงสั่งหยุดเฉพาะเมื่อกำลังอ่านอยู่ แล้ว "รอจนเอนจินเงียบจริง" ก่อนเริ่มอ่านใหม่
  const wasBusy = synth.speaking || synth.pending;
  if (wasBusy) synth.cancel();
  synth.resume?.(); // บางเบราว์เซอร์ค้างสถานะ "หยุดชั่วคราว" ทำให้ไม่มีเสียง
  const voice = pickThaiVoice(synth);
  const utterances = list.map((t) => {
    const u = new SpeechSynthesisUtterance(t);
    u.lang = "th-TH";
    u.rate = rate;
    u.pitch = 1;
    u.volume = 1;
    if (voice) u.voice = voice;
    return u;
  });
  keepAlive = utterances;
  const t0 = Date.now();
  const start = () => {
    if (token !== speakToken) return; // มีคำสั่งใหม่กว่าแล้ว ข้ามอันนี้ ไม่ให้อ่านซ้อน
    if ((synth.speaking || synth.pending) && Date.now() - t0 < 500) {
      setTimeout(start, 30);
      return;
    }
    utterances.forEach((u) => synth.speak(u));
  };
  setTimeout(start, wasBusy ? 50 : 0);
}

