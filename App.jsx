// เลือกเสียงไทยของเบราว์เซอร์ (ใช้เมื่อสำรอง): ใช้เสียงที่ผู้เรียนเลือกไว้ก่อน ถ้าไม่มีให้เลือกเสียงที่ดีที่สุดในเครื่อง
function pickThaiVoice(synth) {
  const th = synth.getVoices().filter(isThaiVoice);
  if (!th.length) return null;
  const chosen = preferredVoiceName && th.find((v) => v.name === preferredVoiceName);
  if (chosen) return chosen;
  const score = (v) =>
    (/natural|neural|online|premium|enhanced/i.test(v.name) ? 4 : 0) +
    (/google|microsoft|apple/i.test(v.name) ? 1 : 0) +
    (v.default ? 1 : 0);
  return [...th].sort((a, b) => score(b) - score(a))[0];
}

