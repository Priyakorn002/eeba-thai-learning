const DAILY_TOPIC_KEYS = ["numbers", "time", "days", "months", "greetings", "family", "colors", "food", "places", "shopping"];
const topicNames = (key) => {
  const [zh, th] = TOPICS[key].title.split(" / ");
  return { th, zh };
};
function buildLesson4Questions(sub) {
  const keys = sub && sub !== "all" ? [sub] : DAILY_TOPIC_KEYS;
  const cats = keys.map((k) => ({ ...topicNames(k), items: TOPICS[k].sections.flatMap((sec) => sec.items) }));
  const everything = cats.flatMap((c) => c.items);
  const gens = cats.flatMap((cat) => {
    const label = `${cat.th} ${cat.zh}`;
    // ตัวเลือกหลอกมาจากหมวดเดียวกันก่อน (ยากขึ้น) และไม่ซ้ำความหมาย/โรมัน/คำกับคำตอบ
    const wrongFor = (it, f, items = cat.items) => {
      const ok = (x) => x[1] !== it[1] && x[4] !== it[4] && x[3] !== it[3];
      const same = items.filter(ok);
      return (same.length >= 5 ? same : everything.filter(ok)).map(f);
    };
    const explain = (it, q, sayText) => q && {
      ...q,
      say: sayText,
      explain: [
        `หมวด ${cat.th}: คำว่า “${it[1]}” อ่านว่า ${it[2]} (${it[3]}) แปลว่า ${it[4]}${it[0] ? ` · เลขไทย ${toThaiDigits(it[0])}` : ""}`,
        `(类别“${cat.zh}”：泰语词 “${it[1]}” 读作 ${it[2]}，罗马音 ${it[3]}，意思是“${it[4]}”${it[0] ? `，泰文数字 ${toThaiDigits(it[0])}` : ""})`,
      ],
    };
    const withNum = cat.items.filter((x) => x[0]);
    const list = [
      () => { const it = pick(cat.items); return explain(it, makeQ(`“${it[1]}” แปลเป็นภาษาจีนว่าอะไร (“${it[1]}” 的中文意思是？) [${label}]`, it[4], wrongFor(it, (x) => x[4])), it[1]); },
      () => { const it = pick(cat.items); return explain(it, makeQ(`ภาษาจีนว่า “${it[4]}” ภาษาไทยคือคำใด (“${it[4]}” 的泰语怎么说？) [${label}]`, it[1], wrongFor(it, (x) => x[1]))); },
      () => { const it = pick(cat.items); return explain(it, makeQ(`“${it[1]}” เขียนด้วยโรมัน (RTGS) ว่าอย่างไร (罗马音是？) [${label}]`, it[3], wrongFor(it, (x) => x[3])), it[1]); },
      () => { const it = pick(cat.items); return explain(it, makeQ(`โรมัน “${it[3]}” คือคำไทยคำใด (罗马音 “${it[3]}” 是哪个泰语词？) [${label}]`, it[1], wrongFor(it, (x) => x[1]))); },
      () => { const it = pick(cat.items.filter((x) => x[2].includes("-"))); return explain(it, makeQ(`“${it[1]}” อ่านแยกพยางค์ว่าอย่างไร (“${it[1]}” 的分音节读法是？) [${label}]`, it[2], wrongFor(it, (x) => x[2]).filter((r) => r.includes("-"))), it[1]); },
    ];
    if (withNum.length >= 5) {
      list.push(
        () => { const it = pick(withNum); return explain(it, makeQ(`เลขไทย ${toThaiDigits(it[0])} ตรงกับคำใด (泰文数字 ${toThaiDigits(it[0])} 对应哪个词？) [${label}]`, it[1], wrongFor(it, (x) => x[1], withNum))); },
        () => { const it = pick(withNum); return explain(it, makeQ(`“${it[1]}” เขียนเป็นเลขไทยว่าอย่างไร (“${it[1]}” 用泰文数字怎么写？) [${label}]`, toThaiDigits(it[0]), wrongFor(it, (x) => toThaiDigits(x[0]), withNum)), it[1]); },
      );
    }
    return list;
  });
  return fillQuiz([], gens);
}

