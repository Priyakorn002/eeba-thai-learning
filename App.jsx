function WritingPad({ glyph, onPracticed }) {
  const canvasRef = useRef(null);
  const drawing = useRef(false);

  // พิกัดเมาส์/นิ้ว -> พิกัดภายใน canvas (รองรับตอนที่ canvas ถูกย่อ/ขยายด้วย CSS)
  const point = (e) => {
    const c = canvasRef.current;
    const r = c.getBoundingClientRect();
    return [((e.clientX - r.left) * c.width) / r.width, ((e.clientY - r.top) * c.height) / r.height];
  };

  const start = (e) => {
    const c = canvasRef.current;
    if (!c) return;
    const ctx = c.getContext("2d");
    ctx.lineWidth = 10;
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    ctx.strokeStyle = "#7c3aed";
    const [x, y] = point(e);
    ctx.beginPath();
    ctx.moveTo(x, y);
    ctx.lineTo(x + 0.01, y); // ให้การแตะครั้งเดียวเป็นจุด
    ctx.stroke();
    drawing.current = true;
    c.setPointerCapture(e.pointerId);
  };

  const move = (e) => {
    if (!drawing.current || !canvasRef.current) return;
    const ctx = canvasRef.current.getContext("2d");
    const [x, y] = point(e);
    ctx.lineTo(x, y);
    ctx.stroke();
  };

  const stop = () => { drawing.current = false; };

  const clear = () => {
    const c = canvasRef.current;
    if (c) c.getContext("2d").clearRect(0, 0, c.width, c.height);
  };

  return (
    <>
      <h3>练习书写 / ฝึกเขียน</h3>
      <p>ลากตามตัวอย่างหรือฝึกเขียนในพื้นที่ด้านล่าง / ลากนิ้วหรือเมาส์เพื่อฝึกเขียน</p>
      <div style={{ position: "relative", maxWidth: 440 }}>
        <div style={{ position: "absolute", inset: 0, display: "grid", placeItems: "center", fontSize: 180, color: "#e5d9ed", pointerEvents: "none" }}>{glyph}</div>
        <canvas
          ref={canvasRef}
          width={880}
          height={500}
          style={{ display: "block", width: "100%", aspectRatio: "440 / 250", border: "2px dashed #c8afd9", borderRadius: 12, touchAction: "none", position: "relative", boxSizing: "border-box" }}
          onPointerDown={start}
          onPointerMove={move}
          onPointerUp={stop}
          onPointerCancel={stop}
        />
      </div>
      <div style={{ display: "flex", gap: 10, marginTop: 12, flexWrap: "wrap" }}>
        <button type="button" style={S.secondary} onClick={clear}>清除 / ล้างกระดาน</button>
        <button type="button" style={S.primary} onClick={onPracticed}>标记已练习 / บันทึกว่าฝึกแล้ว</button>
      </div>
      <p style={{ fontSize: 13, color: "#786d80", marginTop: 12 }}>
        提示：此版本提供描写参考与自由书写练习；准确的逐笔动画数据将在后续补充。 / เวอร์ชันนี้มีตัวอักษรจางเป็นแนวทางและกระดานฝึกเขียน ส่วนแอนิเมชันลำดับขีดที่ถูกต้องจะเพิ่มภายหลัง
      </p>
    </>
  );
}

