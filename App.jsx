const quotedThai = (text) => [...new Set([...String(text).matchAll(/“([^”]+)”/g)].map((m) => m[1]).filter((w) => /[\u0E00-\u0E7F]/.test(w)))];

function Quiz({ questions, say, onFinish, onRetry, onBack }) {
  const [index, setIndex] = useState(0);
  const [score, setScore] = useState(0);
  const [answer, setAnswer] = useState("");
  const [checked, setChecked] = useState(false);
  const [finished, setFinished] = useState(false);

  const QUESTIONS = questions;
  const q = QUESTIONS[index];
  const isCorrect = answer === q.correct;

  const submit = () => {
    if (!answer || checked) return;
    if (isCorrect) setScore((s) => s + 1);
    setChecked(true);
  };

  const next = () => {
    if (index < QUESTIONS.length - 1) {
      setIndex((i) => i + 1);
      setAnswer("");
      setChecked(false);
    } else {
      setFinished(true);
      onFinish();
    }
  };

  if (finished) {
    return (
      <section style={{ ...S.card, maxWidth: 680, textAlign: "center" }}>
        <h2>ทำแบบฝึกหัดเสร็จแล้ว! (测验完成)</h2>
        <p style={{ fontSize: 40, fontWeight: 700, margin: "12px 0" }}>{score}/{QUESTIONS.length}</p>
        <p>{score === QUESTIONS.length ? "เยี่ยมมาก! (太棒了)" : score >= QUESTIONS.length * 0.6 ? "ดีมาก (不错)" : "สู้ต่อไป ลองทบทวนบทเรียนอีกครั้ง (继续加油，再复习一遍)"}</p>
        <div style={{ display: "flex", gap: 10, justifyContent: "center", flexWrap: "wrap" }}>
          <button type="button" style={S.primary} onClick={onRetry}>ทำชุดใหม่ (换一套题)</button>
          <button type="button" style={S.secondary} onClick={onBack}>เลือกหมวดอื่น (选择其他测验)</button>
        </div>
      </section>
    );
  }

  return (
    <section style={{ ...S.card, maxWidth: 680 }}>
      <p style={{ margin: "0 0 6px", fontWeight: 600 }}>ข้อ {index + 1} จาก {QUESTIONS.length} (第 {index + 1} 题，共 {QUESTIONS.length} 题)</p>
      <div style={{ height: 8, borderRadius: 999, background: "#efe4f8", overflow: "hidden", marginBottom: 6 }}>
        <div style={{ height: "100%", width: `${((index + (checked ? 1 : 0)) / QUESTIONS.length) * 100}%`, background: "linear-gradient(90deg,#8901d7,#e0338f)", transition: "width .3s ease" }} />
      </div>
      <h2>{q.q}</h2>
      {say && quotedThai(q.q).length > 0 && (
        <div style={{ display: "flex", gap: 8, flexWrap: "wrap", marginBottom: 14 }}>
          {quotedThai(q.q).map((w) => (
            <button key={w} type="button" style={S.secondary} onClick={() => say(w)}>
              🔊 ฟัง “{w}” (听)
            </button>
          ))}
        </div>
      )}

      <div style={{ display: "grid", gap: 10 }}>
        {q.a.map((opt) => {
          let border = answer === opt ? "2px solid #8901d7" : "1px solid #dcc9ee";
          let bg = answer === opt ? "#f6ebff" : "#fff";
          if (checked && opt === q.correct) { border = "2px solid #16834b"; bg = "#e3f6ec"; }
          else if (checked && opt === answer) { border = "2px solid #c0392b"; bg = "#fdecea"; }
          return (
            <button
              type="button"
              key={opt}
              style={{ ...S.secondary, textAlign: "left", border, background: bg, padding: "14px 18px", fontSize: 16, lineHeight: 1.5 }}
              onClick={() => !checked && setAnswer(opt)}
            >
              {checked && opt === q.correct ? "✓ " : checked && opt === answer ? "✗ " : ""}{opt}
            </button>
          );
        })}
      </div>
      {checked && (
        <p style={{ fontWeight: 700, color: isCorrect ? "#16834b" : "#c0392b" }}>
          {isCorrect ? "ถูกต้อง! (答对了)" : "คำตอบที่ถูกคือ " + q.correct + " (正确答案)"}
        </p>
      )}
      {checked && !isCorrect && q.explain && (
        <div role="note" style={{ background: "#fff4d6", border: "1px solid #f0d58a", borderRadius: 12, padding: "12px 14px", lineHeight: 1.8, color: "#4a3a00" }}>
          <b>เฉลย (解析)</b>
          {q.explain.map((line) => <div key={line}>{line}</div>)}
        </div>
      )}
      {!checked ? (
        <button type="button" style={{ ...S.primary, marginTop: 18, opacity: answer ? 1 : 0.5 }} onClick={submit} disabled={!answer}>ตรวจคำตอบ (提交答案)</button>
      ) : (
        <button type="button" style={{ ...S.primary, marginTop: 18 }} onClick={next}>
          {index < QUESTIONS.length - 1 ? "ข้อต่อไป (下一题)" : "ดูผลคะแนน (查看结果)"}
        </button>
      )}
    </section>
  );
}

