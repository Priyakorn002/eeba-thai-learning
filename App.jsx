const QUIZ_LEN = 10;
const shuffle = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};
// สร้างข้อสอบ 1 ข้อ: ตัวเลือกไม่ซ้ำกัน และมีคำตอบที่ถูกอยู่ 1 ข้อเสมอ (ถ้าตัวเลือกหลอกไม่พอ คืน null)
function makeQ(q, correct, pool, n = 4) {
  const wrong = shuffle([...new Set(pool)].filter((x) => x !== correct)).slice(0, n - 1);
  if (!correct || wrong.length < Math.min(n - 1, 2)) return null;
  return { q, correct, a: shuffle([correct, ...wrong]) };
}

