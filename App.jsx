function consonantVariants(c) {
  const [name, word] = CONSONANT_SPOKEN[c[0]] || [consonantName(c[0]), c[1]];
  const all = [
    ...(USER_SPEECH[c[0]] ? [["user", USER_SPEECH[c[0]]]] : []),
    ["pair", [name, word]],
    ["single", [`${name} ${word}`]],
    ["letter", [name[0], word]],
    ["lead", [`ตัว ${name} ${word}`]],
    ["word", [word]],
    ["orig", [name, c[1]]],
  ];
  const seen = new Set(); // ตัดแบบที่ให้ข้อความเหมือนกันทิ้ง จะได้ไม่กดแล้วได้ยินซ้ำ
  return all.filter(([, parts]) => {
    const key = parts.join("|");
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
const defaultVariantId = (c) => (USER_SPEECH[c[0]] ? "user" : DEFAULT_VARIANT[c[0]] || "pair");
const variantIndex = (c, pick) => {
  const list = consonantVariants(c);
  const i = list.findIndex(([id]) => id === (pick || defaultVariantId(c)));
  return { list, index: Math.max(i, 0) };
};
// ชุดเสียงที่จะอ่านของพยัญชนะหนึ่งตัว ตามแบบที่เลือก (pick) หรือแบบเริ่มต้น
const consonantSpeech = (c, pick) => {
  const { list, index } = variantIndex(c, pick);
  return list[index][1];
};
// รหัสแบบถัดไปที่จะสลับไป
const nextVariantId = (c, pick) => {
  const { list, index } = variantIndex(c, pick);
  return list[(index + 1) % list.length][0];
};
